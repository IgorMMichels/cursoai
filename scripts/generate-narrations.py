"""Generate matching audio and word timestamps from the published lesson text."""
import asyncio
import hashlib
import html
import json
from pathlib import Path
import subprocess
import unicodedata

import edge_tts

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'public' / 'audio' / 'narrated'
VOICE = 'pt-BR-AntonioNeural'
RATE = '-5%'


def normalized(text):
    letters, positions = [], []
    for index, char in enumerate(text):
        for letter in unicodedata.normalize('NFKD', char.casefold()):
            if letter.isalnum():
                letters.append(letter)
                positions.append(index)
    return ''.join(letters), positions


def align(transcript, boundaries):
    source, positions = normalized(transcript)
    cursor = 0
    words = []
    for event in boundaries:
        token, _ = normalized(html.unescape(event['text']))
        if not token:
            continue
        if not source.startswith(token, cursor):
            raise ValueError(f"Word boundary differs from script at {cursor}: {event['text']!r}")
        last = cursor + len(token)
        words.append({
            'start': round(event['offset'] / 10_000_000, 4),
            'end': round((event['offset'] + event['duration']) / 10_000_000, 4),
            'charStart': positions[cursor],
            'charEnd': positions[last - 1] + 1,
        })
        cursor = last
    if cursor != len(source) or not words:
        raise ValueError('Word boundaries do not cover the complete script')
    return words


async def generate(item, semaphore):
    async with semaphore:
        fingerprint = hashlib.sha256((VOICE + RATE + item['transcript']).encode()).hexdigest()[:12]
        stem = f"{item['id']}-{fingerprint}"
        audio = OUTPUT / f'{stem}.mp3'
        metadata = OUTPUT / f'{stem}.json'
        if audio.exists() and metadata.exists():
            saved = json.loads(metadata.read_text(encoding='utf-8'))
            if saved['transcript'] == item['transcript']:
                print(f"Cached {item['id']}", flush=True)
                return item['id'], saved['track']
        for attempt in range(3):
            try:
                boundaries = []
                temporary = audio.with_suffix('.mp3.part')
                with temporary.open('wb') as file:
                    stream = edge_tts.Communicate(item['transcript'], VOICE, rate=RATE, boundary='WordBoundary')
                    async for chunk in stream.stream():
                        if chunk['type'] == 'audio':
                            file.write(chunk['data'])
                        elif chunk['type'] == 'WordBoundary':
                            boundaries.append(chunk)
                words = align(item['transcript'], boundaries)
                duration = float(subprocess.check_output([
                    'ffprobe', '-v', 'error', '-show_entries', 'format=duration',
                    '-of', 'default=noprint_wrappers=1:nokey=1', str(temporary),
                ], encoding='utf-8').strip())
                if words[-1]['end'] > duration + .15:
                    raise ValueError('Word timing exceeds audio duration')
                track = {
                    'src': f'/audio/narrated/{stem}.mp3',
                    'captionsSrc': f'/audio/narrated/{stem}.json',
                    'transcript': item['transcript'], 'summary': item['summary'],
                    'duration': duration, 'voice': VOICE,
                }
                temporary.replace(audio)
                metadata.write_text(json.dumps({'transcript': item['transcript'], 'words': words, 'track': track}, ensure_ascii=False), encoding='utf-8')
                print(f"Generated {item['id']}: {duration:.1f}s, {len(words)} word cues", flush=True)
                return item['id'], track
            except Exception:
                if attempt == 2:
                    raise
                await asyncio.sleep(2 * (attempt + 1))


async def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    source = subprocess.check_output(['node', 'scripts/export-narration-source.mjs'], cwd=ROOT, encoding='utf-8')
    items = json.loads(source)
    semaphore = asyncio.Semaphore(2)
    tracks = dict(await asyncio.gather(*(generate(item, semaphore) for item in items)))
    destination = ROOT / 'src' / 'lib' / 'generated' / 'narrations.ts'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("// Generated by scripts/generate-narrations.py. Do not edit.\nimport type { NarrationTrack } from '../narration-script'\n\nexport const narrations: Record<string, NarrationTrack> = " + json.dumps(tracks, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Published {len(tracks)} narrations', flush=True)


if __name__ == '__main__':
    asyncio.run(main())
